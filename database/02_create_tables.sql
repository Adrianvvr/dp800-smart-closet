-- Proyecto SmartClosetAI: Tablas evolucionadas (IDENTITY, SEQUENCE, JSON, VECTOR)

USE SmartClosetAI;
GO

SET NOCOUNT ON;
GO

-- Limpieza del esquema previo en orden inverso
DROP TABLE IF EXISTS DOCUMENTOS_BUSQUEDA;
DROP TABLE IF EXISTS VALORACIONES_OUTFIT;
DROP TABLE IF EXISTS OUTFIT_PRENDA;
DROP TABLE IF EXISTS OUTFITS;
DROP TABLE IF EXISTS PRENDAS;
DROP TABLE IF EXISTS OCASIONES;
DROP TABLE IF EXISTS MARCAS;
DROP TABLE IF EXISTS USUARIOS;
DROP SEQUENCE IF EXISTS seq_documento_id;
GO

-- Secuencia para tabla de documentos
CREATE SEQUENCE seq_documento_id
    AS INT
    START WITH 1
    INCREMENT BY 1;
GO

-- Usuarios (soporte Dynamic Data Masking posteriormente en email)
CREATE TABLE USUARIOS (
    id INT IDENTITY(1,1) CONSTRAINT PK_USUARIOS PRIMARY KEY CLUSTERED,
    name NVARCHAR(100) NOT NULL,
    email NVARCHAR(150) NOT NULL CONSTRAINT UQ_USUARIOS_EMAIL UNIQUE,
    email_verified_at DATETIME2 NULL,
    password NVARCHAR(255) NOT NULL,
    remember_token NVARCHAR(100) NULL,
    created_at DATETIME2 NOT NULL CONSTRAINT DF_USUARIOS_CREATED DEFAULT SYSDATETIME(),
    updated_at DATETIME2 NOT NULL CONSTRAINT DF_USUARIOS_UPDATED DEFAULT SYSDATETIME(),
    CONSTRAINT CK_USUARIOS_EMAIL_FORMATO CHECK (email LIKE '%_@__%.__%')
);
GO

-- Marcas (soporte Fuzzy String Matching)
CREATE TABLE MARCAS (
    id INT IDENTITY(1,1) CONSTRAINT PK_MARCAS PRIMARY KEY CLUSTERED,
    nombre NVARCHAR(100) NOT NULL CONSTRAINT UQ_MARCAS_NOMBRE UNIQUE,
    sitio_web NVARCHAR(255) NULL,
    created_at DATETIME2 NOT NULL CONSTRAINT DF_MARCAS_CREATED DEFAULT SYSDATETIME(),
    updated_at DATETIME2 NOT NULL CONSTRAINT DF_MARCAS_UPDATED DEFAULT SYSDATETIME()
);
GO

-- Ocasiones
CREATE TABLE OCASIONES (
    id INT IDENTITY(1,1) CONSTRAINT PK_OCASIONES PRIMARY KEY CLUSTERED,
    nombre NVARCHAR(50) NOT NULL CONSTRAINT UQ_OCASIONES_NOMBRE UNIQUE,
    descripcion NVARCHAR(255) NULL,
    nivel_formalidad TINYINT NOT NULL CONSTRAINT CK_OCASIONES_FORMALIDAD CHECK (nivel_formalidad BETWEEN 1 AND 5)
);
GO

-- Prendas (atributos dinámicos en JSON nativo)
CREATE TABLE PRENDAS (
    id INT IDENTITY(1,1) CONSTRAINT PK_PRENDAS PRIMARY KEY CLUSTERED,
    usuario_id INT NOT NULL,
    marca_id INT NULL,
    nombre NVARCHAR(150) NOT NULL,
    descripcion NVARCHAR(1000) NULL,
    talla NVARCHAR(20) NULL,
    categoria NVARCHAR(50) NOT NULL,
    color_principal NVARCHAR(50) NOT NULL,
    atributos_json JSON NULL,
    precio_compra DECIMAL(10,2) NULL CONSTRAINT CK_PRENDAS_PRECIO CHECK (precio_compra >= 0),
    foto_url NVARCHAR(500) NULL,
    esta_limpia BIT NOT NULL CONSTRAINT DF_PRENDAS_LIMPIA DEFAULT 1,
    fecha_ensuciado DATETIME2 NULL,
    fecha_ultimo_uso DATETIME2 NULL,
    contador_usos INT NOT NULL CONSTRAINT DF_PRENDAS_USOS DEFAULT 0 CONSTRAINT CK_PRENDAS_USOS CHECK (contador_usos >= 0),
    created_at DATETIME2 NOT NULL CONSTRAINT DF_PRENDAS_CREATED DEFAULT SYSDATETIME(),
    updated_at DATETIME2 NOT NULL CONSTRAINT DF_PRENDAS_UPDATED DEFAULT SYSDATETIME(),
    CONSTRAINT FK_PRENDAS_USUARIOS FOREIGN KEY (usuario_id) REFERENCES USUARIOS(id),
    CONSTRAINT FK_PRENDAS_MARCAS FOREIGN KEY (marca_id) REFERENCES MARCAS(id)
);
GO

-- Outfits
CREATE TABLE OUTFITS (
    id INT IDENTITY(1,1) CONSTRAINT PK_OUTFITS PRIMARY KEY CLUSTERED,
    usuario_id INT NOT NULL,
    ocasion_id INT NULL,
    nombre NVARCHAR(150) NOT NULL,
    notas NVARCHAR(1000) NULL,
    fecha_planificada DATE NULL,
    fue_usado BIT NOT NULL CONSTRAINT DF_OUTFITS_USADO DEFAULT 0,
    created_at DATETIME2 NOT NULL CONSTRAINT DF_OUTFITS_CREATED DEFAULT SYSDATETIME(),
    updated_at DATETIME2 NOT NULL CONSTRAINT DF_OUTFITS_UPDATED DEFAULT SYSDATETIME(),
    CONSTRAINT FK_OUTFITS_USUARIOS FOREIGN KEY (usuario_id) REFERENCES USUARIOS(id),
    CONSTRAINT FK_OUTFITS_OCASIONES FOREIGN KEY (ocasion_id) REFERENCES OCASIONES(id)
);
GO

-- Relación Outfits - Prendas
CREATE TABLE OUTFIT_PRENDA (
    outfit_id INT NOT NULL,
    prenda_id INT NOT NULL,
    CONSTRAINT PK_OUTFIT_PRENDA PRIMARY KEY CLUSTERED (outfit_id, prenda_id),
    CONSTRAINT FK_OUTFIT_PRENDA_OUTFITS FOREIGN KEY (outfit_id) REFERENCES OUTFITS(id) ON DELETE CASCADE,
    CONSTRAINT FK_OUTFIT_PRENDA_PRENDAS FOREIGN KEY (prenda_id) REFERENCES PRENDAS(id) ON DELETE CASCADE
);
GO

-- Valoraciones
CREATE TABLE VALORACIONES_OUTFIT (
    id INT IDENTITY(1,1) CONSTRAINT PK_VALORACIONES_OUTFIT PRIMARY KEY CLUSTERED,
    outfit_id INT NOT NULL,
    usuario_id INT NOT NULL,
    puntuacion TINYINT NOT NULL CONSTRAINT CK_VALORACIONES_PUNTUACION CHECK (puntuacion BETWEEN 1 AND 5),
    comentario NVARCHAR(1000) NULL,
    created_at DATETIME2 NOT NULL CONSTRAINT DF_VALORACIONES_CREATED DEFAULT SYSDATETIME(),
    CONSTRAINT FK_VALORACIONES_OUTFITS FOREIGN KEY (outfit_id) REFERENCES OUTFITS(id) ON DELETE CASCADE,
    CONSTRAINT FK_VALORACIONES_USUARIOS FOREIGN KEY (usuario_id) REFERENCES USUARIOS(id),
    CONSTRAINT UQ_VALORACION_USUARIO_OUTFIT UNIQUE (outfit_id, usuario_id)
);
GO

-- Documentos para IA (Chunks y VECTOR nativo con aislamiento multi-tenant)
CREATE TABLE DOCUMENTOS_BUSQUEDA (
    id INT NOT NULL CONSTRAINT DF_DOC_ID DEFAULT (NEXT VALUE FOR seq_documento_id),
    usuario_id INT NOT NULL,
    tipo_origen NVARCHAR(20) NOT NULL CONSTRAINT CK_DOC_TIPO CHECK (tipo_origen IN (N'PRENDA', N'OUTFIT', N'VALORACION')),
    origen_id INT NOT NULL,
    titulo NVARCHAR(200) NOT NULL,
    contenido_texto NVARCHAR(MAX) NOT NULL,
    metadatos_json JSON NULL,
    embedding VECTOR(768) NULL,
    updated_at DATETIME2 NOT NULL CONSTRAINT DF_DOC_UPDATED DEFAULT SYSDATETIME(),
    CONSTRAINT PK_DOCUMENTOS_BUSQUEDA PRIMARY KEY CLUSTERED (id),
    CONSTRAINT FK_DOCUMENTOS_USUARIOS FOREIGN KEY (usuario_id) REFERENCES USUARIOS(id) ON DELETE CASCADE,
    CONSTRAINT UQ_DOCUMENTO_ORIGEN UNIQUE (tipo_origen, origen_id)
);
GO